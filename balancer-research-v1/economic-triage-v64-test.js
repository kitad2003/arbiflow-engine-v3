'use strict';
const assert=require('node:assert/strict');
const {ethers}=require('ethers');
const {WETH,triage,assess}=require('./economic-triage-v64');
const USDT='0xdAC17F958D2ee523a2206206994597C13D831ec7';
const eth=ethers.parseEther;
const reserves={poolA:{r0:eth('0.001').toString(),r1:'1000000000'},poolB:{r0:eth('10').toString(),r1:'1000000000'}};
const quote={sizeRaw:eth('0.00001').toString(),returnedRaw:eth('0.00002').toString(),inputToken:WETH};
const r=triage(quote,{token0:WETH,token1:USDT,reserves});
assert(r.rejectionReasons.includes('WETH_LIQUIDITY_BELOW_1_ETH_PER_POOL'));
assert(r.rejectionReasons.includes('WETH_INPUT_BELOW_0_01'));
assert(r.rejectionReasons.includes('GAS_UNVERIFIED'));
assert.equal(r.executionEligible,false);
const large={poolA:{r0:eth('100').toString(),r1:'1000000000'},poolB:{r0:eth('100').toString(),r1:'1000000000'}};
const good=triage({sizeRaw:eth('1').toString(),returnedRaw:eth('1.1').toString(),inputToken:WETH},{token0:WETH,token1:USDT,reserves:large,gasUnits:300000,gasPriceWei:1000000000n,loanFeeBps:9,builderBidWei:0});
assert(BigInt(good.indicativeNetWei)>0n);
assert.equal(good.executionEligible,false);
assert(good.rejectionReasons.includes('POST_TARGET_ATOMIC_SIMULATION_NOT_VERIFIED'));
const noPrice=triage({...quote,inputToken:USDT},{token0:WETH,token1:USDT,reserves:large});
assert(noPrice.rejectionReasons.includes('INPUT_NOT_WETH_REQUIRE_VERIFIED_PRICE_CONVERSION'));
(async()=>{const x=await assess(null,'A','B',{evaluateImpl:async()=>({token0:WETH,token1:USDT,reserves,quotes:[quote],blockNumber:1})});assert.equal(x.qualified,0);console.log(JSON.stringify({build:'BALANCER_ECONOMIC_TRIAGE_V64',unitAssertionsPassed:9}))})().catch(e=>{console.error(e);process.exitCode=1});
