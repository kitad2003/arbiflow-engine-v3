'use strict';
const assert=require('node:assert/strict');
const {Interface,AbiCoder}=require('ethers');
const {decodeUniversalIntent}=require('./universal-router-intent-v7');
const iface=new Interface(['function execute(bytes commands,bytes[] inputs,uint256 deadline) payable']);
const coder=AbiCoder.defaultAbiCoder();
const router='0x1111111111111111111111111111111111111111';
const a='0x2222222222222222222222222222222222222222';
const b='0x3333333333333333333333333333333333333333';
const input=coder.encode(['address','uint256','uint256','address[]','bool'],[a,1000n,900n,[a,b],true]);
const tx={to:router,input:iface.encodeFunctionData('execute',[ '0x08',[input],9999999999n])};
const good=decodeUniversalIntent(tx,{allowlistedAddresses:[router]});
assert.equal(good.decoded,true);assert.equal(good.swaps.length,1);
assert.equal(good.swaps[0].command,'V2_SWAP_EXACT_IN');
assert.deepEqual(good.swaps[0].path.map(x=>x.toLowerCase()),[a,b]);
assert.equal(good.executionEligible,false);assert.equal(good.profitVerified,false);
assert.equal(decodeUniversalIntent(tx,{allowlistedAddresses:[]}).decoded,false);
const unknown={...tx,input:iface.encodeFunctionData('execute',['0x3f',[input],9999999999n])};
assert.equal(decodeUniversalIntent(unknown,{allowlistedAddresses:[router]}).decoded,false);
console.log('V7_UNIVERSAL_ROUTER_OFFLINE_TEST_PASS');
