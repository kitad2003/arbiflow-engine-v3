assert.equal(sweepV2TradeSizes({amountsRaw:Array(65).fill('1'),first,second}).reason,'INVALID_SIZE_LIST');
assert.equal(sweepV2TradeSizes({amountsRaw:['100'],first,second:{...second,blockTag:124}}).valid,false);
